export function getListing(slug: string) {
  return listings.find((l) => l.slug === slug);
}

export function listingsByCategory(category: Category | "all") {
  if (category === "all") return listings;
  return listings.filter((l) => l.category === category);
}

export function featuredListings() {
  return listings.filter((l) => l.featured);
}

export function searchListings(query: string) {
  const q = query.trim().toLowerCase();
  if (!q) return listings;
  return listings.filter((l) => {
    const hay = [
      l.name,
      l.kind,
      l.location,
      l.area,
      l.description,
      ...l.tags,
      ...l.bestFor,
    ]
      .join(" ")
      .toLowerCase();
    return hay.includes(q);
  });
}

export function nearbyListings(slug: string, limit = 4) {
  const current = getListing(slug);
  if (!current) return listings.slice(0, limit);
  return listings
    .filter((l) => l.slug !== slug && (l.area === current.area || l.category === current.category))
    .slice(0, limit);
}
